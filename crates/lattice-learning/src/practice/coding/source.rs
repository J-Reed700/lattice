//! Where coding problems come from: `ProblemSource` trait and `GeneratedProblems`
//! which uses an LLM to generate problems, proves them, and reports progress via `BuildSteps`.

use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use tokio_util::sync::CancellationToken;

use crate::drills::runner::CodeRunner;
use crate::practice::coding::harness::CaseHarness;
use crate::practice::coding::problem::{
    Case, CodingTask, Difficulty, Misreading, Problem, ProblemSpec, Setting,
};
use crate::practice::coding::proof::{prove_misreadings, prove_reference, ProofError};
use lattice_core::application::ports::llm_port::{CompletionInput, CompletionRequest, LLMPort};
use lattice_core::domain::learning::practice::problem_patterns::statement_names_pattern;
use lattice_core::shared::error::{AppError, Result};

/// The maximum number of generation attempts before failing.
pub const MAX_BUILD_ATTEMPTS: usize = 3;

/// The three named build steps in order: drafting, proving reference, and verifying misreadings.
pub const STEP_DRAFTING: &str = "Drafting problem statement and cases";
pub const STEP_PROVING_REFERENCE: &str = "Proving reference solution";
pub const STEP_VERIFYING_MISREADINGS: &str = "Verifying misreadings";

pub const BUILD_STEP_NAMES: [&str; 3] = [
    STEP_DRAFTING,
    STEP_PROVING_REFERENCE,
    STEP_VERIFYING_MISREADINGS,
];

/// Progress reporter for problem build steps.
#[async_trait]
pub trait BuildSteps: Send + Sync {
    async fn step(&self, index: u32, message: &str) -> Result<bool>;
}

/// A request to generate or locate a coding problem.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct ProblemRequest {
    pub program_id: String,
    pub lesson_id: Option<String>,
    pub task: CodingTask,
    pub setting: Setting,
    pub language: String,
    pub difficulty: Difficulty,
    pub focus: Option<String>,
    #[serde(default)]
    pub preparing_for: Option<String>,
    #[serde(default)]
    pub patterns: Vec<String>,
}

/// A candidate problem generated by the model before verification.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedProblemDraft {
    pub spec: ProblemSpec,
    pub reference: String,
    pub misreadings: Vec<Misreading>,
    pub cases: Vec<Case>,
}

/// A source of proven coding problems.
#[async_trait]
pub trait ProblemSource: Send + Sync {
    async fn problem(
        &self,
        request: &ProblemRequest,
        steps: &dyn BuildSteps,
        cancel: CancellationToken,
    ) -> Result<Problem>;
}

/// Generates coding problems via LLM and proves them through the code runner and harness.
pub struct GeneratedProblems<'a> {
    pub llm: &'a dyn LLMPort,
    pub runner: &'a dyn CodeRunner,
    pub harness: &'a dyn CaseHarness,
}

impl<'a> GeneratedProblems<'a> {
    pub fn new(
        llm: &'a dyn LLMPort,
        runner: &'a dyn CodeRunner,
        harness: &'a dyn CaseHarness,
    ) -> Self {
        Self {
            llm,
            runner,
            harness,
        }
    }

    /// Verifies that the problem statement does not name its pattern.
    pub fn validate_statement(&self, statement: &str, patterns: &[String]) -> Result<()> {
        if let Some(named) = statement_names_pattern(statement, patterns) {
            return Err(AppError::InvalidInput(format!(
                "Problem statement must not name pattern '{named}'"
            )));
        }
        Ok(())
    }

    fn extract_json<'b>(&self, text: &'b str) -> &'b str {
        let trimmed = text.trim();
        if let Some(rest) = trimmed.strip_prefix("```json") {
            if let Some(inner) = rest.strip_suffix("```") {
                return inner.trim();
            }
        } else if let Some(rest) = trimmed.strip_prefix("```") {
            if let Some(inner) = rest.strip_suffix("```") {
                return inner.trim();
            }
        }
        trimmed
    }
}

#[async_trait]
impl<'a> ProblemSource for GeneratedProblems<'a> {
    async fn problem(
        &self,
        request: &ProblemRequest,
        steps: &dyn BuildSteps,
        cancel: CancellationToken,
    ) -> Result<Problem> {
        let mut last_feedback: Option<String> = None;

        for _attempt in 0..MAX_BUILD_ATTEMPTS {
            if cancel.is_cancelled() {
                return Err(AppError::InvalidState("Cancelled".into()));
            }

            // Step 0: Drafting problem statement and cases
            steps.step(0, STEP_DRAFTING).await?;

            let prompt = match &last_feedback {
                Some(feedback) => format!(
                    "Generate a coding problem for difficulty {:?} in {}. Note previous failure: {feedback}",
                    request.difficulty, request.language
                ),
                None => format!(
                    "Generate a coding problem for difficulty {:?} in {}.",
                    request.difficulty, request.language
                ),
            };

            let completion_req = CompletionRequest {
                input: vec![CompletionInput::Message {
                    role: "user".into(),
                    content: prompt,
                }],
                ..Default::default()
            };

            let response = self.llm.complete(&completion_req).await?;
            let json_text = self.extract_json(&response.text);
            let candidate: GeneratedProblemDraft =
                serde_json::from_str(json_text).map_err(|e| {
                    AppError::InvalidInput(format!("Failed to parse problem draft JSON: {e}"))
                })?;

            // Validate that statement does not name its pattern
            if let Err(e) =
                self.validate_statement(&candidate.spec.statement, &candidate.spec.patterns)
            {
                last_feedback = Some(format!("The statement named a pattern: {e}"));
                continue;
            }

            // Step 1: Proving reference solution
            steps.step(1, STEP_PROVING_REFERENCE).await?;
            if cancel.is_cancelled() {
                return Err(AppError::InvalidState("Cancelled".into()));
            }

            let reference_ms = match prove_reference(
                self.runner,
                self.harness,
                &candidate.spec,
                &candidate.reference,
                &candidate.cases,
                cancel.clone(),
            )
            .await
            {
                Ok(ms) => ms,
                Err(ProofError::ReferenceFailed {
                    failed_cases,
                    results: _,
                }) => {
                    last_feedback = Some(format!(
                        "The reference solution failed on cases: {:?}. Please provide a working reference solution.",
                        failed_cases
                    ));
                    continue;
                }
                Err(ProofError::Cancelled) => {
                    return Err(AppError::InvalidState("Cancelled".into()))
                }
                Err(e) => {
                    last_feedback = Some(format!("Proof error on reference: {:?}", e));
                    continue;
                }
            };

            // Step 2: Verifying misreadings
            steps.step(2, STEP_VERIFYING_MISREADINGS).await?;
            if cancel.is_cancelled() {
                return Err(AppError::InvalidState("Cancelled".into()));
            }

            let proven_misreadings = match prove_misreadings(
                self.runner,
                self.harness,
                &candidate.spec,
                &candidate.misreadings,
                &candidate.cases,
                cancel.clone(),
            )
            .await
            {
                Ok(mis) => mis,
                Err(ProofError::InsufficientMisreadings { killed, required }) => {
                    last_feedback = Some(format!(
                        "Only {killed} misreadings were killed by cases, but {required} are required."
                    ));
                    continue;
                }
                Err(ProofError::Cancelled) => {
                    return Err(AppError::InvalidState("Cancelled".into()))
                }
                Err(e) => {
                    last_feedback = Some(format!("Proof error on misreadings: {:?}", e));
                    continue;
                }
            };

            return Ok(Problem {
                spec: candidate.spec,
                reference: candidate.reference,
                misreadings: proven_misreadings,
                cases: candidate.cases,
                reference_ms,
            });
        }

        Err(AppError::InvalidInput(format!(
            "Could not prove problem after {MAX_BUILD_ATTEMPTS} attempts: {}",
            last_feedback.unwrap_or_default()
        )))
    }
}

