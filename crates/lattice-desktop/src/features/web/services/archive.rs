fn without_verbatim_prefix(path: &Path) -> PathBuf {
    use std::path::{Component, Prefix};
    let mut components = path.components();
    match components.next() {
        Some(Component::Prefix(prefix)) => match prefix.kind() {
            Prefix::VerbatimDisk(letter) => {
                let mut plain = PathBuf::from(format!("{}:", char::from(letter)));
                plain.extend(components);
                plain
            }
            _ => path.to_path_buf(),
        },
        _ => path.to_path_buf(),
    }
}

/// Web archive service for managing markdown-based article archives
pub struct WebArchiveService {
    /// Base directory for archive (~/.lattice/web-archive)
    base_dir: PathBuf,
    /// Every spelling of `base_dir` a path may carry (as configured, with
    /// symlinks resolved, and without a Windows verbatim prefix), computed once
    /// so `owns` needs no filesystem calls.
    owned_roots: Vec<PathBuf>,
}

impl WebArchiveService {
    /// Creates the service over `~/.lattice/web-archive`, ensuring its README.md
    /// exists.
    ///
    /// # Errors
    /// - `AppError::ConfigError` if home directory cannot be determined
    /// - `AppError::Io` if directory creation fails
    pub fn new() -> Result<Self> {
        Ok(Self::with_base_dir(Self::default_root()?))
    }

    /// `~/.lattice/web-archive`, where saved articles live. Backups pack and
    /// restore this folder; both resolve it through `shared::fs::roots`.
    ///
    /// # Errors
    /// - `AppError::InvalidState` if home directory cannot be determined
    pub fn default_root() -> Result<PathBuf> {
        lattice_core::shared::fs::roots::web_archive_root()
    }

    /// Create a service rooted at an explicit directory.
    ///
    /// Used by tests and by anything that needs an archive somewhere other
    /// than the user's home directory.
    pub fn with_base_dir(base_dir: PathBuf) -> Self {
        let resolved =
            resolve_against_existing_ancestor(&base_dir).unwrap_or_else(|_| base_dir.clone());
        let mut owned_roots = vec![base_dir.clone()];
        for root in [without_verbatim_prefix(&resolved), resolved] {
            if !owned_roots.contains(&root) {
                owned_roots.push(root);
            }
        }
        Self {
            base_dir,
            owned_roots,
        }
    }

    /// Root of this archive.
    pub fn base_dir(&self) -> &Path {
        &self.base_dir
    }

    /// Creates the base directory and README.md if they are missing.
    ///
    /// # Errors
    /// - `AppError::Io` if directory creation or file writing fails
    pub async fn initialize(&self) -> Result<()> {
        fs::create_dir_all(&self.base_dir)
            .await
            .map_err(|e| AppError::Io {
                message: format!("Failed to create archive directory: {}", e),
                kind: format!("{:?}", e.kind()),
            })?;

        self.ensure_readme().await?;

        Ok(())
    }

    /// Ensure README.md exists in the archive directory
    async fn ensure_readme(&self) -> Result<()> {
        let readme_path = self.base_dir.join("README.md");

        if !readme_path.exists() {
            fs::write(&readme_path, README_CONTENT)
                .await
                .map_err(|e| AppError::Io {
                    message: format!("Failed to write README: {}", e),
                    kind: format!("{:?}", e.kind()),
                })?;
        }

        Ok(())
    }
}

#[async_trait]
impl ArticleArchive for WebArchiveService {
    async fn delete_article(&self, path: &Path) -> Result<()> {
        // Determine what to delete based on path type
        let path_to_delete = if path.is_dir() {
            // Directory path: remove entire directory (legacy)
            path.to_path_buf()
        } else if path.file_name() == Some(std::ffi::OsStr::new("article.md")) {
            // article.md path: remove parent directory (new format)
            path.parent()
                .map(|p| p.to_path_buf())
                .unwrap_or_else(|| path.to_path_buf())
        } else {
            // Single file: remove just the file (legacy)
            match fs::remove_file(path).await {
                Ok(()) => return Ok(()),
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
                Err(e) => {
                    return Err(AppError::Io {
                        message: format!("Failed to delete article file: {}", e),
                        kind: format!("{:?}", e.kind()),
                    })
                }
            }
        };

        match fs::remove_dir_all(&path_to_delete).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(AppError::Io {
                message: format!("Failed to delete article directory: {}", e),
                kind: format!("{:?}", e.kind()),
            }),
        }
    }

    fn owns(&self, path: &Path) -> bool {
        reject_parent_components(path).is_ok()
            && self.owned_roots.iter().any(|root| path.starts_with(root))
    }

    fn is_saved_article(&self, path: &Path) -> bool {
        path.file_name() == Some(std::ffi::OsStr::new("article.md")) && self.owns(path)
    }

    async fn saved_article(&self, path: &Path) -> Option<SavedArticle> {
        if !self.is_saved_article(path) || !is_file(path).await {
            return None;
        }
        let dir = path.parent()?;
        let page = dir.join("page.html");
        let page = is_file(&page).await.then_some(page);
        let facts = match fs::read_to_string(dir.join("metadata.json")).await {
            Ok(content) => serde_json::from_str::<SavedFacts>(&content).unwrap_or_default(),
            Err(_) => SavedFacts::default(),
        };
        Some(SavedArticle {
            text: path.to_path_buf(),
            page,
            title: facts.title,
            url: facts.url,
            links: facts.links,
        })
    }
}

