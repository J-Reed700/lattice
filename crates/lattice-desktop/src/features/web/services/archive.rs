/// Structured metadata stored in metadata.json
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ArticleMetadata {
    /// Original URL
    pub url: String,

    /// Article title
    pub title: String,

    /// Author name (if available)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub author: Option<String>,

    /// Publication date (if available)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub published_date: Option<DateTime<Utc>>,

    /// When article was archived
    pub archived_at: DateTime<Utc>,

    /// Word count
    pub word_count: usize,

    /// Estimated reading time in minutes
    pub reading_time_minutes: i64,

    /// Outgoing links captured from the article HTML
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub links: Vec<String>,
}

async fn is_file(path: &Path) -> bool {
    fs::metadata(path)
        .await
        .map(|metadata| metadata.is_file())
        .unwrap_or(false)
}

/// What `metadata.json` says about a saved article, read leniently: older
/// files lack fields `ArticleMetadata` requires.
#[derive(Debug, Default, Deserialize)]
struct SavedFacts {
    #[serde(default)]
    title: Option<String>,
    #[serde(default)]
    url: Option<String>,
    #[serde(default)]
    links: Vec<String>,
}

