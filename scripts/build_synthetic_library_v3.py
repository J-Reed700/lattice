def check_integrity(lib):
    texts = [(doc.id, doc.text) for doc in lib.docs]
    problems = []

    for needle in lib.needles:
        for token in needle["tokens"]:
            found = sorted(doc_id for doc_id, text in texts if token in text)
            if found != needle["docs"]:
                problems.append(
                    f"needle {token!r} appears in {found} but was declared for {needle['docs']}")

    for token in lib.absent:
        found = sorted(doc_id for doc_id, text in texts if token in text)
        if found:
            problems.append(f"unanswerable token {token!r} leaked into {found}")

    known = set(lib.by_id)
    for query in lib.queries:
        positives = {doc for doc, grade in query["relevance"].items() if grade > 0}
        if not set(query["relevance"]).issubset(known):
            problems.append(f"{query['id']}: labels reference unknown documents")
        if not set(query["spans"]).issubset(positives):
            problems.append(f"{query['id']}: answer spans outside the relevant documents")
        if positives and not query["spans"]:
            problems.append(f"{query['id']}: answerable query without an answer span")
        if len(positives) > 3:
            problems.append(f"{query['id']}: more positives than recall@5 can reward")
        for dimension in query["dimensions"] or ["<none>"]:
            if dimension not in DIMENSIONS:
                problems.append(f"{query['id']}: unknown dimension {dimension!r}")
        if query["exempt"]:
            continue
        for doc_id, keys in query["spans"].items():
            passage = " ".join(lib.by_id[doc_id].passage(key) for key in keys)
            text = query["text"]
            quoted = next((text[at:at + MAX_QUOTED_CHARACTERS]
                           for at in range(len(text) - MAX_QUOTED_CHARACTERS + 1)
                           if text[at:at + MAX_QUOTED_CHARACTERS] in passage), None)
            if quoted:
                problems.append(f"{query['id']}: quotes its own answer ({quoted!r})")

    counts = {}
    for query in lib.queries:
        for dimension in query["dimensions"]:
            counts[dimension] = counts.get(dimension, 0) + 1
    for dimension in DIMENSIONS:
        if counts.get(dimension, 0) < MIN_PER_DIMENSION:
            problems.append(f"dimension {dimension!r} has {counts.get(dimension, 0)} queries, "
                            f"needs {MIN_PER_DIMENSION}")
    if not 150 <= len(lib.queries) <= 200:
        problems.append(f"{len(lib.queries)} queries, wanted between 150 and 200")
    if not 300 <= len(lib.docs) <= 400:
        problems.append(f"{len(lib.docs)} documents, wanted between 300 and 400")

    if problems:
        raise ValueError("fixture integrity failed:\n  " + "\n  ".join(problems))
    return counts


def check_spans(dataset):
    """Every answer span must decode and must sit inside its own document."""
    bodies = {doc["id"]: doc["text"].encode("utf-8") for doc in dataset["documents"]}
    for query in dataset["queries"]:
        for doc_id, spans in query.get("answer_spans", {}).items():
            body = bodies[doc_id]
            for start, end in spans:
                if not 0 <= start < end <= len(body):
                    raise ValueError(f"{query['id']}: span out of range in {doc_id}")
                body[start:end].decode("utf-8")


