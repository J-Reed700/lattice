    struct RecordingSteps {
        steps: Mutex<Vec<(u32, String)>>,
    }

    impl RecordingSteps {
        fn new() -> Self {
            Self {
                steps: Mutex::new(Vec::new()),
            }
        }
    }

    #[async_trait]
    impl BuildSteps for RecordingSteps {
        async fn step(&self, index: u32, message: &str) -> Result<bool> {
            if let Ok(mut lock) = self.steps.lock() {
                lock.push((index, message.to_string()));
            }
            Ok(true)
        }
    }

    fn sample_draft_json(reference_code: &str) -> String {
        let draft = GeneratedProblemDraft {
            spec: ProblemSpec {
                title: "Two Sum".into(),
                statement: "Find two numbers in nums that add up to target.".into(),
                signature: Signature {
                    function: "two_sum".into(),
                    params: vec![
                        Param {
                            name: "nums".into(),
                            annotation: "list[int]".into(),
                        },
                        Param {
                            name: "target".into(),
                            annotation: "int".into(),
                        },
                    ],
                    returns: "list[int]".into(),
                },
                constraints: vec!["2 <= nums.length <= 10^4".into()],
                clarifications: Vec::new(),
                language: "python".into(),
                difficulty: Difficulty::Easy,
                target_complexity: "O(n) time, O(n) space".into(),
                patterns: vec!["hash_map_lookup".into()],
                starter: "def two_sum(nums, target):\n    pass\n".into(),
            },
            reference: reference_code.into(),
            misreadings: vec![
                Misreading {
                    id: "mis-fails-1".into(),
                    description: "Returns empty list, failing case-1".into(),
                    code: "def two_sum(nums, target): return []".into(),
                    killed_by: Vec::new(),
                },
                Misreading {
                    id: "mis-fails-2".into(),
                    description: "Returns [1, 2], failing case-1".into(),
                    code: "def two_sum(nums, target): # mis-fails-2\n    return [1, 2]".into(),
                    killed_by: Vec::new(),
                },
            ],
            cases: vec![
                Case {
                    id: "case-1".into(),
                    category: "basic".into(),
                    args: vec!["[2, 7, 11, 15]".into(), "9".into()],
                    expected: Some("[0, 1]".into()),
                    compare: Compare::Exact,
                    visibility: Visibility::Example,
                    scale: false,
                },
                Case {
                    id: "case-2".into(),
                    category: "duplicates".into(),
                    args: vec!["[3, 3]".into(), "6".into()],
                    expected: Some("[0, 1]".into()),
                    compare: Compare::Exact,
                    visibility: Visibility::Hidden,
                    scale: false,
                },
            ],
        };
        serde_json::to_string(&draft).unwrap()
    }

    #[tokio::test]
    async fn test_reference_solution_fails_case_is_rejected_and_asked_for_again() {
        // First response has failing reference ("return []"), second response has passing reference
        let first_resp = sample_draft_json("def two_sum(nums, target): return []");
        let second_resp = sample_draft_json("def two_sum(nums, target): return [0, 1]");

        let llm = MockLLM::new(vec![first_resp, second_resp]);
        let runner = MockRunner;
        let harness = MockHarness;
        let generator = GeneratedProblems::new(&llm, &runner, &harness);
        let steps = RecordingSteps::new();

        let request = ProblemRequest {
            program_id: "prog-1".into(),
            lesson_id: Some("les-1".into()),
            task: CodingTask::Problem,
            setting: Setting::Coached,
            language: "python".into(),
            difficulty: Difficulty::Easy,
            focus: None,
            preparing_for: None,
            patterns: vec!["hash_map_lookup".into()],
        };

        let result = generator
            .problem(&request, &steps, CancellationToken::new())
            .await;
        assert!(
            result.is_ok(),
            "problem generation should succeed after re-asking: {:?}",
            result.err()
        );
        assert!(
            llm.calls() >= 2,
            "LLM must be queried again when reference solution fails a case"
        );
    }

    #[test]
    fn test_problem_statement_naming_pattern_is_refused() {
        let llm = MockLLM::new(Vec::new());
        let runner = MockRunner;
        let harness = MockHarness;
        let generator = GeneratedProblems::new(&llm, &runner, &harness);

        let statement_with_pattern =
            "Solve this problem by using a Hash Map Lookup to store items.";
        let patterns = vec!["hash_map_lookup".to_string()];
        let result = generator.validate_statement(statement_with_pattern, &patterns);
        assert!(
            result.is_err(),
            "problem statement naming its pattern must be refused"
        );

        let clean_statement = "Given a list of numbers, find two numbers that sum to the target.";
        let clean_result = generator.validate_statement(clean_statement, &patterns);
        assert!(
            clean_result.is_ok(),
            "problem statement without pattern name must be accepted"
        );
    }

    #[tokio::test]
    async fn test_build_steps_records_three_named_build_steps_in_order() {
        let resp = sample_draft_json("def two_sum(nums, target): return [0, 1]");
        let llm = MockLLM::new(vec![resp]);
        let runner = MockRunner;
        let harness = MockHarness;
        let generator = GeneratedProblems::new(&llm, &runner, &harness);
        let steps = RecordingSteps::new();

        let request = ProblemRequest {
            program_id: "prog-1".into(),
            lesson_id: Some("les-1".into()),
            task: CodingTask::Problem,
            setting: Setting::Coached,
            language: "python".into(),
            difficulty: Difficulty::Easy,
            focus: None,
            preparing_for: None,
            patterns: vec!["two_pointers".into()],
        };

        let result = generator
            .problem(&request, &steps, CancellationToken::new())
            .await;
        assert!(
            result.is_ok(),
            "problem generation should succeed: {:?}",
            result.err()
        );

        let recorded = steps.steps.lock().unwrap().clone();
        assert_eq!(recorded.len(), 3, "must record exactly 3 build steps");
        assert_eq!(recorded[0].0, 0);
        assert_eq!(recorded[0].1, BUILD_STEP_NAMES[0]);
        assert_eq!(recorded[1].0, 1);
        assert_eq!(recorded[1].1, BUILD_STEP_NAMES[1]);
        assert_eq!(recorded[2].0, 2);
        assert_eq!(recorded[2].1, BUILD_STEP_NAMES[2]);
    }
