//! Plugin routes for the generated commands.
//!
//! Every Lattice command is registered inside an inlined Tauri plugin, so the
//! webview invokes it as `plugin:<plugin>|<command>`. tauri-specta names one
//! plugin per builder and these bindings come from one builder, so it emits
//! bare names. The owner of each command is read from its
//! `<plugin>:allow-<command>` grant in `capabilities/main.json`, which
//! `scripts/check-tauri-command-inventory.py` holds equal to the plugin's
//! `generate_handler!`. A generated command without exactly one owner stops
//! generation: it could not be invoked anyway.

use serde_json::Value;
use std::collections::BTreeMap;

const INVOKE: &str = "TAURI_INVOKE(\"";

const ROUTES_HEADER: &str = "\
// Auto-generated by src-tauri/src/bin/export_bindings/main.rs. DO NOT EDIT.
// To regenerate: cargo run --features bindings-export --bin export_bindings
//
// The inlined plugin that registers each command in src/lib/bindings.ts, read
// from its `<plugin>:allow-<command>` grant in src-tauri/capabilities/main.json.
";

/// Command name to the plugins that grant it.
pub fn command_owners(capabilities: &str) -> Result<BTreeMap<String, Vec<String>>, String> {
    let capabilities: Value = serde_json::from_str(capabilities)
        .map_err(|error| format!("capabilities/main.json is not valid JSON: {error}"))?;
    let permissions = capabilities
        .get("permissions")
        .and_then(Value::as_array)
        .ok_or("capabilities/main.json has no `permissions` array")?;
    let mut owners: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for permission in permissions {
        // A grant is an identifier, or an object scoping one.
        let identifier = permission
            .as_str()
            .or_else(|| permission.get("identifier").and_then(Value::as_str));
        // `core:window:allow-…` splits into `core` and `window:allow-…`, so
        // core's nested grants never read as a plugin command.
        let Some((plugin, grant)) = identifier.and_then(|id| id.split_once(':')) else {
            continue;
        };
        if let Some(command) = grant.strip_prefix("allow-") {
            owners
                .entry(command.replace('-', "_"))
                .or_default()
                .push(plugin.to_string());
        }
    }
    Ok(owners)
}

/// Rewrites each `TAURI_INVOKE("command"` in the generated bindings to the
/// command's plugin route, returning the bindings and the command → plugin map.
pub fn qualify_commands(
    bindings: &str,
    owners: &BTreeMap<String, Vec<String>>,
) -> Result<(String, BTreeMap<String, String>), String> {
    let mut routes = BTreeMap::new();
    let mut qualified = String::with_capacity(bindings.len() + bindings.len() / 16);
    let mut rest = bindings;
    while let Some(at) = rest.find(INVOKE) {
        let (before, after) = rest.split_at(at + INVOKE.len());
        qualified.push_str(before);
        let end = after
            .find('"')
            .ok_or("a generated TAURI_INVOKE has an unterminated command name")?;
        let command = &after[..end];
        let plugin = match owners.get(command).map(Vec::as_slice) {
            Some([plugin]) => plugin,
            Some([]) | None => {
                return Err(format!(
                    "`{command}` has no `<plugin>:allow-{}` grant in capabilities/main.json",
                    command.replace('_', "-")
                ))
            }
            Some(plugins) => {
                return Err(format!(
                    "`{command}` is granted by several plugins ({}); a command name must have one owner",
                    plugins.join(", ")
                ))
            }
        };
        qualified.push_str(&format!("plugin:{plugin}|{command}"));
        routes.insert(command.to_string(), plugin.clone());
        rest = &after[end..];
    }
    qualified.push_str(rest);
    Ok((qualified, routes))
}

/// The renderer's route table: `COMMAND_PLUGINS` and the `CommandName` union.
pub fn render_routes(routes: &BTreeMap<String, String>) -> String {
    let mut rendered = format!("{ROUTES_HEADER}\nexport const COMMAND_PLUGINS = {{\n");
    for (command, plugin) in routes {
        rendered.push_str(&format!("  {command}: '{plugin}',\n"));
    }
    rendered.push_str("} as const;\n\nexport type CommandName = keyof typeof COMMAND_PLUGINS;\n");
    rendered
}

#[cfg(test)]
mod tests {
    use super::{command_owners, qualify_commands, render_routes};

    const CAPABILITIES: &str = r#"{
        "permissions": [
            "core:default",
            "core:window:allow-create",
            "explorer:allow-explorer-list-dir",
            { "identifier": "file:allow-read-file-bytes", "allow": [] },
            "dialog:allow-open",
            "shell:allow-open"
        ]
    }"#;

    #[test]
    fn each_plugin_grant_names_its_command_with_underscores() -> Result<(), String> {
        let owners = command_owners(CAPABILITIES)?;
        assert_eq!(
            owners.get("explorer_list_dir"),
            Some(&vec!["explorer".to_string()])
        );
        assert_eq!(
            owners.get("read_file_bytes"),
            Some(&vec!["file".to_string()])
        );
        assert!(
            !owners.contains_key("create"),
            "core's window grants are not plugin commands"
        );
        Ok(())
    }

    #[test]
    fn generated_invocations_become_plugin_routes() -> Result<(), String> {
        let owners = command_owners(CAPABILITIES)?;
        let bindings = "await TAURI_INVOKE(\"explorer_list_dir\", { root, path })\n\
                        await TAURI_INVOKE(\"read_file_bytes\", { path })\n";
        let (qualified, routes) = qualify_commands(bindings, &owners)?;
        assert_eq!(
            qualified,
            "await TAURI_INVOKE(\"plugin:explorer|explorer_list_dir\", { root, path })\n\
             await TAURI_INVOKE(\"plugin:file|read_file_bytes\", { path })\n"
        );
        assert_eq!(
            routes.get("explorer_list_dir").map(String::as_str),
            Some("explorer")
        );
        assert_eq!(
            routes.get("read_file_bytes").map(String::as_str),
            Some("file")
        );
        Ok(())
    }

    #[test]
    fn a_command_without_a_grant_stops_generation() -> Result<(), String> {
        let owners = command_owners(CAPABILITIES)?;
        let routed = qualify_commands("TAURI_INVOKE(\"compact_conversation\")", &owners);
        assert!(routed.is_err_and(|error| error.contains("allow-compact-conversation")));
        Ok(())
    }

    #[test]
    fn a_command_granted_by_two_plugins_stops_generation() -> Result<(), String> {
        let owners = command_owners(CAPABILITIES)?;
        let routed = qualify_commands("TAURI_INVOKE(\"open\")", &owners);
        assert!(routed.is_err_and(|error| error.contains("dialog, shell")));
        Ok(())
    }

    #[test]
    fn the_route_table_lists_commands_in_order() {
        let routes = [
            ("search_fast", "search"),
            ("cluster_vault_run", "corpus-shape"),
        ]
        .into_iter()
        .map(|(command, plugin)| (command.to_string(), plugin.to_string()))
        .collect();
        let rendered = render_routes(&routes);
        assert!(rendered.contains(
            "export const COMMAND_PLUGINS = {\n  cluster_vault_run: 'corpus-shape',\n  search_fast: 'search',\n} as const;"
        ));
        assert!(rendered.ends_with("export type CommandName = keyof typeof COMMAND_PLUGINS;\n"));
    }
}
