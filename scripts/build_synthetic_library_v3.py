def _transcript_block(rng, speakers, minute):
    lines = []
    for step in range(rng.randint(4, 8)):
        speaker = rng.choice(speakers)
        body = sentence(rng.choice(D.MEETING_SENTENCES + D.OPS_SENTENCES), rng)
        lines.append(f"[{minute // 60:02d}:{minute % 60:02d}:{step * 7 % 60:02d}] {speaker}: {body}")
