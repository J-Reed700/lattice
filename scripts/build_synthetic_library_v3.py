def rng_for(name):
    """A stream per section, so adding a section does not reshuffle the others."""
    return random.Random(f"{SEED}#{name}")


SLOT = re.compile(r"\{(\w+)(?::(\d+)-(\d+))?\}")
CONSTANTS = {"COMPANY": D.COMPANY, "OWNER": D.OWNER, "PARTNER": D.PARTNER, "HOUSE": D.HOUSE}


def fill(template, rng, **extra):
    def replace(match):
        name, low, high = match.group(1), match.group(2), match.group(3)
        if name in extra:
            return str(extra[name])
        if name in CONSTANTS:
            return CONSTANTS[name]
        if low is not None:
            return str(rng.randint(int(low), int(high)))
        return rng.choice(D.POOLS[name])
    return SLOT.sub(replace, template)


def sentence(template, rng, **extra):
    text = fill(template, rng, **extra)
    return text[:1].upper() + text[1:]


def paragraph(rng, templates, low=3, high=6, **extra):
    # Sampled rather than chosen, so one paragraph never repeats a template.
    count = min(rng.randint(low, high), len(templates))
    return " ".join(sentence(template, rng, **extra)
                    for template in rng.sample(templates, count))


def prose(rng, templates, paragraphs, low=3, high=6, **extra):
    return [paragraph(rng, templates, low, high, **extra) for _ in range(paragraphs)]


