CONFUSIONS = [("rn", "m"), ("m", "rn"), ("l", "1"), ("1", "l"), ("O", "0"), ("0", "O"),
              ("cl", "d"), ("c", "e"), ("s", "5"), ("B", "8"), ("g", "9"), ("ii", "n")]


def ocr_damage(text, rng, protect=(), rate=0.014, page_every=900):
    """Corrupt a scan the way a cheap OCR pass does, leaving protected tokens intact.

    A real scan damages the identifier as often as the prose, but a fixture whose
    needle token has been mangled cannot be proved unique, so the tokens survive
    and everything around them does not.
    """
    pieces, index = [], 0
    matches = sorted((m for token in protect for m in re.finditer(re.escape(token), text)),
                     key=lambda m: m.start())
    for match in matches:
        if match.start() < index:
            continue
        pieces.append((text[index:match.start()], True))
        pieces.append((match.group(0), False))
        index = match.end()
    pieces.append((text[index:], True))
    joined = "".join(_damage_chunk(chunk, rng, rate) if mutable else chunk
                     for chunk, mutable in pieces)
    return _paginate(joined, page_every)


def _damage_chunk(text, rng, rate):
    out, index = [], 0
    while index < len(text):
        if rng.random() < rate:
            roll = rng.random()
            if roll < 0.55:
                for source, target in CONFUSIONS:
                    if text.startswith(source, index):
                        out.append(target)
                        index += len(source)
                        break
                else:
                    out.append(text[index])
                    index += 1
            elif roll < 0.75 and text[index] == " ":
                index += 1  # dropped space
            elif roll < 0.9 and text[index].isalpha() and index + 3 < len(text):
                out.append(text[index] + "-\n")  # hyphenation across a line break
                index += 1
            else:
                out.append(text[index] * 2)  # doubled character
                index += 1
        else:
            out.append(text[index])
            index += 1
    return "".join(out)


def _paginate(text, page_every):
    """Repeat the same scanner header and footer every notional page."""
    header = "[ QG-ARC scan | Quillon Grid internal | page %d ]"
    footer = "-- end of page %d -- do not remove from site --"
    out, page, index = [], 1, 0
    while index < len(text):
        cut = text.find(" ", index + page_every)
        cut = len(text) if cut < 0 else cut
        out.append(header % page)
        out.append(text[index:cut].strip())
        out.append(footer % page)
        index, page = cut, page + 1
    return "\n".join(out)


