def build_long(lib):
    rng = rng_for("long")
    for doc_id, title, shape, target, style in LONG_PLAN:
        doc = Doc(id=doc_id, title=title, kind=SHAPE_KIND[shape], collection="work/long-form",
                  effective_date=lib.tokens.date())
        pool = STYLE_POOLS[style]
        doc.add(f"# {title}")
        speakers = [rng.choice(D.POOLS["person"]) for _ in range(5)]
        size, minute, part, section, clause = 0, 9 * 60, 0, 0, 0
        while size < target:
            if shape == "tree":
                if section % 4 == 0:
                    part += 1
                    doc.add(f"## Part {part} — {rng.choice(D.HEADING_PARTS)}")
                section += 1
                doc.add(f"### {section}. {rng.choice(D.HEADING_SECTIONS)}")
                for _ in range(rng.randint(2, 4)):
                    doc.add(f"#### {rng.choice(D.HEADING_SUBS)}")
                    block = paragraph(rng, pool, 4, 7)
                    doc.add(block)
                    size += len(block)
            elif shape == "clauses":
                section += 1
                doc.add(f"## Section {section}. {rng.choice(D.HEADING_PARTS)}")
                for _ in range(rng.randint(3, 6)):
                    clause += 1
                    block = f"{section}.{clause} " + paragraph(rng, pool, 3, 5)
                    doc.add(block)
                    size += len(block)
            elif shape == "transcript":
                block = _transcript_block(rng, speakers, minute)
                minute += rng.randint(2, 6)
                doc.add(block)
                size += len(block)
            else:
                block = paragraph(rng, pool, 6, 10)
                doc.add(block)
                size += len(block)
        doc.meta = {"shape": shape, "style": style}
        lib.add(doc)

    long_docs = [lib.by_id[plan[0]] for plan in LONG_PLAN]
    for order, doc in enumerate(long_docs):
        style = doc.meta["style"]
        for slot, fraction in enumerate((0.12, 0.5, 0.88)):
            value_kind, template, question = LONG_NEEDLES[style][slot]
            anchor = lib.tokens.anchor()
            value = lib.tokens.of_kind(value_kind)
            body = template.replace("{anchor}", anchor).replace("{value}", value)
            if style == "meeting":
                body = f"[{10 + slot:02d}:{order * 3 % 60:02d}:00] " \
                       f"{D.POOLS['person'][order % len(D.POOLS['person'])]}: {body}"
            doc.mark_at(f"needle{slot}", body, max(1, int(len(doc.blocks) * fraction)))
            lib.needle([anchor, value], [doc.id])
            doc.meta[f"question{slot}"] = question

    # Twelve tail needles keep v2's "long-context tail facts" comparable; the rest
    # sit at 12% and 50% depth so oversized chunks cannot be hidden by position.
    asked = [(order, 2) for order in range(len(long_docs)) if order % 4 != 3]
    asked += [(order, 0) for order in range(len(long_docs)) if order % 4 == 3]
    asked += [(1, 1), (9, 1)]
    for order, slot in sorted(asked):
        doc = long_docs[order]
        dimensions = [BURIED, PARAPHRASE]
        if slot == 2:
            dimensions.append(TAIL)
        else:
            dimensions.append(HARD_NEG)
        grades = {other.id: 0 for other in long_docs
                  if other is not doc and other.meta["style"] == doc.meta["style"]}
        grades[doc.id] = 3
        lib.ask(f"v3-buried-{doc.id}-{slot}",
                f"In the {doc.title.lower()}: {doc.meta[f'question{slot}']}",
                "buried needle", dimensions, grades, {doc.id: [f"needle{slot}"]})


