def render(dataset):
    return json.dumps(dataset, indent=2, ensure_ascii=False, allow_nan=False) + "\n"


def summary(dataset):
    counts = {}
    for query in dataset["queries"]:
        for dimension in query["dimensions"]:
            counts[dimension] = counts.get(dimension, 0) + 1
    return {
        "documents": len(dataset["documents"]),
        "queries": len(dataset["queries"]),
        "unanswerable_queries": sum(1 for q in dataset["queries"] if not q["relevance"]),
        "total_characters": sum(len(doc["text"]) for doc in dataset["documents"]),
        "longest_document_characters": max(len(d["text"]) for d in dataset["documents"]),
        "queries_per_dimension": dict(sorted(counts.items())),
    }


