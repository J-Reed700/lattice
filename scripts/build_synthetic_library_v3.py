VAL_SLOT = re.compile(r"\{val(?::(\w+))?\}")


def build_paraphrase(lib):
    rng = rng_for("paraphrase")
    hosts = {
        "policy": lib.pick("policy-", lambda d: d.id.endswith("-v3")),
        "runbook": lib.pick("runbook-core-"),
        "contract": lib.pick("contract-", lambda d: d.meta.get("vendor")),
    }
    used = {key: 0 for key in hosts}
    for index, item in enumerate(D.PARAPHRASE_FACTS):
        pool = hosts[item["host"]]
        host = pool[used[item["host"]] % len(pool)]
        decoy = pool[(used[item["host"]] + 3) % len(pool)]
        used[item["host"]] += 1
        anchor = lib.tokens.anchor()
        match = VAL_SLOT.search(item["statement"])
        value = lib.tokens.of_kind(match.group(1) or "duration")
        statement = VAL_SLOT.sub(value.replace("\\", r"\\"),
                                 item["statement"].replace("{anchor}", anchor))
        key = f"para{index}"
        host.mark_at(key, "## Standing provision\n" + statement, max(1, len(host.blocks) // 3))
        decoy.mark_at(f"decoy{index}", "## Standing provision\n" + fill(item["decoy"], rng),
                      max(1, len(decoy.blocks) // 3))
        lib.needle([anchor, value], [host.id])
        lib.ask(f"v3-paraphrase-{index:02d}", item["question"], "vocabulary mismatch",
                [PARAPHRASE, HARD_NEG], {host.id: 3, decoy.id: 0}, {host.id: [key]})


