class Tokens:
    """Mints every distinctive string in the corpus.

    Two rules make the uniqueness check meaningful: no token repeats, and no
    token is a substring of another. Without the second rule a search for
    `ERR-4012` would also match `ERR-40128` and the check would be a lie.
    """

    def __init__(self, rng):
        self.rng = rng
        self.issued = list(RESERVED)

    def _keep(self, token):
        for other in self.issued:
            if token in other or other in token:
                return False
        self.issued.append(token)
        return True

    def _mint(self, make, attempts=6000):
        for _ in range(attempts):
            token = make()
            if self._keep(token):
                return token
        raise RuntimeError("token space exhausted")

    def error_code(self):
        return self._mint(lambda: f"ERR-{self.rng.randint(1000, 9999)}")

    def purchase_order(self):
        return self._mint(lambda: f"PO-{self.rng.randint(10000, 99999)}")

    def ticket(self):
        return self._mint(lambda: f"TCK-{self.rng.randint(1000, 9999)}")

    def signal(self):
        return self._mint(lambda: f"SIG-{self.rng.randint(10000, 99999)}")

    def part(self):
        return self._mint(lambda: f"QG-{self.rng.randint(100, 999)}-{self.rng.randint(100, 999)}")

    def release(self):
        return self._mint(
            lambda: f"v{self.rng.randint(2, 9)}.{self.rng.randint(1, 9)}.{self.rng.randint(1, 9)}")

    def date(self):
        return self._mint(
            lambda: f"20{self.rng.randint(25, 34)}-{self.rng.randint(1, 12):02d}-"
                    f"{self.rng.randint(10, 28)}")

    def amount(self):
        # One leading digit everywhere, so no amount can be a substring of another.
        return self._mint(
            lambda: f"£{self.rng.randint(1, 9)},{self.rng.randint(100, 999)}."
                    f"{self.rng.randint(10, 99)}")

    def percent(self):
        # Two integer digits for the same reason.
        return self._mint(lambda: f"{self.rng.randint(11, 89)}.{self.rng.randint(1, 9)} per cent")

    def duration(self, unit=None):
        units = [unit] if unit else ["working days", "calendar days", "hours", "weeks"]
        return self._mint(lambda: f"{self.rng.randint(11, 89)} {self.rng.choice(units)}")

    def measure(self):
        return self._mint(lambda: f"0.0{self.rng.randint(100, 998)} mm")

    ONSETS = ["br", "dr", "fl", "gr", "kr", "pl", "sl", "thr", "tr", "vr", "wr",
              "b", "d", "f", "g", "h", "k", "m", "n", "p", "r", "s", "t", "v", "z"]
    NUCLEI = ["a", "e", "i", "o", "u", "ae", "ea", "ei", "oa", "ou"]
    CODAS = ["ck", "dge", "ft", "ld", "lm", "mb", "nd", "ng", "nt", "rk", "rn",
             "sk", "sp", "st", "th", "ll", "ss", "x"]
    SUFFIXES = ["", "", "ley", "worth", "by", "mere", "ford", "hollow", "stead", "gate", "wick"]

    def anchor(self):
        """A pronounceable invented proper noun that occurs nowhere else."""
        for _ in range(20000):
            word = (self.rng.choice(self.ONSETS) + self.rng.choice(self.NUCLEI)
                    + self.rng.choice(self.CODAS) + self.rng.choice(self.SUFFIXES)).capitalize()
            if len(word) < 7 or word.lower() in BANNED_SUBSTRINGS:
                continue
            if self._keep(word):
                return word
        raise RuntimeError("anchor space exhausted")

    def of_kind(self, kind):
        return {"duration": self.duration, "amount": self.amount, "date": self.date,
                "percent": self.percent, "code": self.error_code,
                "release": self.release, "signal": self.signal}[kind]()


@dataclass
class Doc:
    id: str
    title: str
    kind: str
    collection: str
    language: str = "en"
    effective_date: str = None
    separator: str = "\n\n"
    blocks: list = field(default_factory=list)
    marks: dict = field(default_factory=dict)
    meta: dict = field(default_factory=dict)
    text: str = ""
    spans: dict = field(default_factory=dict)

    def add(self, block):
        self.blocks.append(block)
        return len(self.blocks) - 1

    def extend(self, blocks):
        for block in blocks:
            self.add(block)

    def mark(self, key, block):
        """Append a needle block and remember where it landed."""
        index = self.add(block)
        self.marks[key] = index
        return index

    def mark_at(self, key, block, index):
        """Insert a needle block at a chosen depth, keeping earlier marks valid."""
        self.blocks.insert(index, block)
        for existing, position in list(self.marks.items()):
            if position >= index:
                self.marks[existing] = position + 1
        self.marks[key] = index
        return index

    def passage(self, key):
        return self.blocks[self.marks[key]]

    def finalize(self):
        self.text = self.separator.join(self.blocks)
        offsets, running = [], 0
        for block in self.blocks:
            offsets.append(running)
            running += len(block) + len(self.separator)
        for key, index in self.marks.items():
            start = offsets[index]
            end = start + len(self.blocks[index])
            self.spans[key] = (
                len(self.text[:start].encode("utf-8")),
                len(self.text[:end].encode("utf-8")),
            )

    def record(self):
        row = {"id": self.id, "title": self.title, "kind": self.kind,
               "collection": self.collection, "language": self.language}
        if self.effective_date:
            row["effective_date"] = self.effective_date
        row["text"] = self.text
        return row


class Library:
    def __init__(self):
        self.docs = []
        self.by_id = {}
        self.queries = []
        self.query_ids = set()
        self.needles = []
        self.absent = []
        self.tokens = Tokens(rng_for("tokens"))

    def add(self, doc):
        if doc.id in self.by_id:
            raise ValueError(f"duplicate document id {doc.id}")
        self.docs.append(doc)
        self.by_id[doc.id] = doc
        return doc

    def pick(self, prefix, predicate=None):
        return [d for d in self.docs
                if d.id.startswith(prefix) and (predicate is None or predicate(d))]

    def needle(self, tokens, doc_ids):
        """Assert later that each token occurs in exactly these documents."""
        self.needles.append({"tokens": list(tokens), "docs": sorted(doc_ids)})

    def ask(self, qid, text, category, dimensions, relevance, spans=None, exempt=False):
        if qid in self.query_ids:
            raise ValueError(f"duplicate query id {qid}")
        self.query_ids.add(qid)
        self.queries.append({
            "id": qid, "text": text, "category": category,
            "dimensions": list(dict.fromkeys(dimensions)),
            "relevance": dict(relevance), "spans": spans or {}, "exempt": exempt,
        })

    def finalize(self):
        for doc in self.docs:
            doc.finalize()

    def dataset(self):
        queries = []
        for query in self.queries:
            row = {"id": query["id"], "category": query["category"],
                   "dimensions": query["dimensions"], "text": query["text"],
                   "relevance": query["relevance"]}
            spans = {}
            for doc_id, keys in sorted(query["spans"].items()):
                spans[doc_id] = [list(self.by_id[doc_id].spans[key]) for key in keys]
            if spans:
                row["answer_spans"] = spans
            queries.append(row)
        return {
            "name": NAME,
            "description": DESCRIPTION,
            "dimensions": DIMENSIONS,
            "documents": [doc.record() for doc in self.docs],
            "queries": queries,
        }


